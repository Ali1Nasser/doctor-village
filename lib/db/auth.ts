/* Sessions                                                              */
/* ===================================================================== */

/**
 * Open a session. One year on a trusted device (ADR-009/011) — deliberate, not
 * lazy: residents visit four times a year, and every avoided login is a step
 * where an elderly user could fail. Any sensitive action re-verifies with the
 * passkey regardless, via `reauth_at`.
 */
export async function openSession(
  db: Db, profileId: string, tokenHash: string, now: Clock,
  meta: { ip?: string; userAgent?: string } = {},
): Promise<string> {
  const id = newId('SES');
  const oneYear = plus(now(), 365 * 24 * 3600);
  await db.prepare(
    `INSERT INTO sessions (id, profile_id, token_hash, expires_at, reauth_at, ip, user_agent)
     VALUES (?,?,?,?,?,?,?)`
  ).bind(id, profileId, tokenHash, oneYear, now(), meta.ip ?? null, meta.userAgent ?? null).run();
  await db.prepare(`UPDATE profiles SET last_login_at = ? WHERE id = ?`).bind(now(), profileId).run();
  await db.prepare(
    `INSERT INTO audit_log (id, actor_id, action, entity_table, entity_id, ip, user_agent)
     VALUES (?,?, 'session.open', 'sessions', ?, ?, ?)`
  ).bind(newId('AUD'), profileId, id, meta.ip ?? null, meta.userAgent ?? null).run();
  return id;
}

/**
 * Issue printed single-use recovery codes (R-023).
 *
 * ⚠️ Issuing a new set **retires the previous one**, in the same batch.
 *
 * The first version appended, and a test caught what that means: every
 * activation, every new device, every recovery handed out six MORE codes and
 * left all the old ones live. After three such events a resident has eighteen
 * valid passkey bypasses on eighteen pieces of paper, in drawers and photos and
 * WhatsApp messages, and neither they nor the board has any idea how many exist.
 *
 * The resident's mental model is "here are my codes" — singular, replacing.
 * The system has to match it.
 */
export async function issueRecoveryCodes(
  db: Db, profileId: string, hashes: string[], now?: Clock,
): Promise<void> {
  const stamp = now ? now() : '1970-01-01T00:00:00Z';
  await db.batch([
    // retire every unused code from any previous set
    db.prepare(`UPDATE recovery_codes SET used_at = ? WHERE profile_id = ? AND used_at IS NULL`)
      .bind(stamp, profileId),
    ...hashes.map(h => db.prepare(
      `INSERT INTO recovery_codes (id, profile_id, code_hash) VALUES (?,?,?)`
    ).bind(newId('RCV'), profileId, h)),
  ]);
}

/**
 * Redeem a printed recovery code (R-023).
 *
 * This is a passkey BYPASS, so it is written as tightly as the thing it
 * bypasses: the code is matched by hash, burned by a conditional UPDATE so two
 * simultaneous attempts cannot both win, and **every existing session is
 * revoked** — if somebody else had the phone, recovery must end their access,
 * not run alongside it.
 *
 * Returns the person only on success. A wrong code is indistinguishable from a
 * code belonging to somebody else.
 */
export async function redeemRecoveryCode(
  db: Db, codeHash: string, now: Clock,
): Promise<{ profileId: string; fullName: string; remaining: number } | null> {
  const row = await db.prepare(
    `SELECT rc.id, rc.profile_id, p.full_name
       FROM recovery_codes rc JOIN profiles p ON p.id = rc.profile_id
      WHERE rc.code_hash = ? AND rc.used_at IS NULL AND p.is_active = 1`
  ).bind(codeHash).first<{ id: string; profile_id: string; full_name: string }>();
  if (!row) return null;

  const burned = await db.prepare(
    `UPDATE recovery_codes SET used_at = ? WHERE id = ? AND used_at IS NULL`
  ).bind(now(), row.id).run();
  if (burned.meta.changes !== 1) return null;      // lost the race

  await db.batch([
    // Recovery means "I lost the device." Anything still holding a session on a
    // device the resident no longer controls must lose it now.
    db.prepare(`UPDATE sessions SET revoked_at = ? WHERE profile_id = ? AND revoked_at IS NULL`)
      .bind(now(), row.profile_id),
    // The old passkeys go too. A recovered account with the lost phone's
    // credential still enrolled has not actually been recovered.
    db.prepare(`UPDATE passkeys SET revoked_at = ? WHERE profile_id = ? AND revoked_at IS NULL`)
      .bind(now(), row.profile_id),
    db.prepare(
      `INSERT INTO audit_log (id, actor_id, action, entity_table, entity_id, after_json)
       VALUES (?,?, 'account.recover', 'recovery_codes', ?, ?)`
    ).bind(newId('AUD'), row.profile_id, row.id,
           JSON.stringify({ method: 'printed_code' })),
  ]);

  const left = await db.prepare(
    `SELECT COUNT(*) n FROM recovery_codes WHERE profile_id = ? AND used_at IS NULL`
  ).bind(row.profile_id).first<{ n: number }>();

  return { profileId: row.profile_id, fullName: row.full_name, remaining: left?.n ?? 0 };
}

/** Rate limiting lives in D1 for the same reason challenges do (ADR-017). */
export async function countRecentAttempts(
  db: Db, scope: string, key: string, sinceIso: string,
): Promise<number> {
  const r = await db.prepare(
    `SELECT COUNT(*) n FROM auth_attempts WHERE scope = ? AND key = ? AND created_at > ?`
  ).bind(scope, key, sinceIso).first<{ n: number }>();
  return r?.n ?? 0;
}

export async function recordAttempt(
  db: Db, scope: string, key: string, ok: boolean, now: Clock,
): Promise<void> {
  await db.prepare(
    `INSERT INTO auth_attempts (id, scope, key, ok, created_at) VALUES (?,?,?,?,?)`
  ).bind(newId('ATT'), scope, key, ok ? 1 : 0, now()).run();
}
