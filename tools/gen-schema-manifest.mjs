#!/usr/bin/env node
/**
 * tools/gen-schema-manifest.mjs — the list of database objects the deployed app
 * requires, derived from the migrations rather than written by hand.
 *
 * ## The bug this exists because of (R-125)
 *
 * `wrangler.toml` binds TWO D1 databases and names ONE `migrations_dir`. The
 * receipts database was created, bound, and **never migrated** — it held
 * nothing but Cloudflare's own `_cf_KV` — so every receipt upload on the
 * deployed site returned 500 on `no such table: v_blob_usage`, from the first
 * deployment until somebody drove the site in a browser. Locally both bindings
 * point at the same SQLite file, which has everything, so nothing could see it.
 *
 * A health screen can only report a missing table if it knows which tables are
 * supposed to exist. That list must not be a hand-kept array: the day somebody
 * adds a migration and forgets to update it is the day the check goes quiet
 * about the thing it was built for. So it is GENERATED from `migrations/`, and
 * `tests/access/schema.test.ts` regenerates it and fails if the checked-in file
 * has drifted.
 *
 * ## Why it replays rather than greps
 *
 * `CREATE TABLE x` is not the last word on whether `x` exists: `0026` rebuilds
 * `auth_attempts` by creating `auth_attempts_new`, dropping the original, and
 * renaming. A grep for CREATE reports both names and neither is wrong at the
 * time it was written. So the files are replayed in order and the set is kept
 * current — created, dropped, renamed — which is what the database itself ends
 * up holding.
 *
 * Run: npm run gen:schema
 */

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const MIGRATIONS = join(ROOT, 'migrations');

/**
 * Which migrations reach which database.
 *
 * `npm run db:migrate` applies everything to `DB`. The receipts database takes
 * `0008` and nothing else — the comment in `wrangler.toml` says so, and the
 * reason is ADR-023: a receipt blob must not sit in the same file as a journal
 * line, or the nightly dump drags every image through the restore drill.
 */
const RECEIPTS_ONLY = /^0008_/;

/** Objects a check should care about. Indexes are deliberately absent: a
 *  missing index is slow, a missing table or trigger is broken or unguarded. */
const KINDS = ['table', 'view', 'trigger'];

function replay(files) {
  const live = { table: new Set(), view: new Set(), trigger: new Set() };
  for (const f of files) {
    const sql = readFileSync(join(MIGRATIONS, f), 'utf8')
      // Strip line comments so a `-- CREATE TABLE x` in prose is not an object.
      .replace(/^\s*--.*$/gm, '');

    for (const m of sql.matchAll(
      /CREATE\s+(?:UNIQUE\s+)?(TABLE|VIEW|TRIGGER)\s+(?:IF\s+NOT\s+EXISTS\s+)?["'`]?(\w+)["'`]?/gi)) {
      live[m[1].toLowerCase()].add(m[2]);
    }
    for (const m of sql.matchAll(/DROP\s+(TABLE|VIEW|TRIGGER)\s+(?:IF\s+EXISTS\s+)?["'`]?(\w+)["'`]?/gi)) {
      live[m[1].toLowerCase()].delete(m[2]);
    }
    for (const m of sql.matchAll(/ALTER\s+TABLE\s+["'`]?(\w+)["'`]?\s+RENAME\s+TO\s+["'`]?(\w+)["'`]?/gi)) {
      if (live.table.delete(m[1])) live.table.add(m[2]);
    }
  }
  return live;
}

const files = readdirSync(MIGRATIONS).filter(f => f.endsWith('.sql')).sort();
const ledger = replay(files);
const receipts = replay(files.filter(f => RECEIPTS_ONLY.test(f)));

const list = s => [...s].sort();
const block = (o) => KINDS.map(k =>
  `    ${k}s: [${list(o[k]).map(n => `'${n}'`).join(', ')}],`).join('\n');

const out = `/**
 * lib/db/schema-manifest.ts — GENERATED by \`npm run gen:schema\`. Do not edit.
 *
 * Every table, view and trigger each deployed database is supposed to hold,
 * replayed from \`migrations/\`. \`tests/access/schema.test.ts\` regenerates this
 * and fails if it has drifted, so a new migration cannot land without the
 * health check learning about it.
 *
 * Indexes are omitted on purpose: a missing index is slow, a missing table is
 * broken, and a missing TRIGGER is a control that silently is not there —
 * which is the one this project would least like to discover from a resident.
 */

export interface RequiredObjects {
  tables: readonly string[];
  views: readonly string[];
  triggers: readonly string[];
}

/** The ledger database (\`DB\`): every migration applies to it. */
export const LEDGER_SCHEMA: RequiredObjects = {
${block(ledger)}
} as const;

/**
 * The receipts database (\`RECEIPTS\`): \`0008\` and nothing else (ADR-023).
 * This is the one that shipped empty — see R-125.
 */
export const RECEIPTS_SCHEMA: RequiredObjects = {
${block(receipts)}
} as const;
`;

writeFileSync(join(ROOT, 'lib/db/schema-manifest.ts'), out, 'utf8');
console.log(`  lib/db/schema-manifest.ts`);
console.log(`    ledger   ${list(ledger.table).length} tables · ${list(ledger.view).length} views · ${list(ledger.trigger).length} triggers`);
console.log(`    receipts ${list(receipts.table).length} tables · ${list(receipts.view).length} views · ${list(receipts.trigger).length} triggers`);
